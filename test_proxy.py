    def test_small_icon_and_ui_badge_image_rejection(self):
        """Verify 64x64 UI icons (such as the 863-byte blue cloud badge) are rejected while real >=200x200 images pass."""
        import zlib
        import struct

        def make_png(width: int, height: int, pad_bytes: int = 0) -> bytes:
            ihdr = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
            ihdr_chunk = (
                struct.pack(">I", len(ihdr))
                + b"IHDR"
                + ihdr
                + struct.pack(">I", zlib.crc32(b"IHDR" + ihdr) & 0xFFFFFFFF)
            )
            raw_data = b"\x00" + (b"\x42\x85\xf4" * width)
            compressed = zlib.compress(raw_data)
            idat_chunk = (
                struct.pack(">I", len(compressed))
                + b"IDAT"
                + compressed
                + struct.pack(">I", zlib.crc32(b"IDAT" + compressed) & 0xFFFFFFFF)
            )
            padding = b"" if pad_bytes <= 0 else (
                struct.pack(">I", pad_bytes)
                + b"tEXt"
                + (b"x" * pad_bytes)
                + struct.pack(">I", 0)
            )
            iend_chunk = struct.pack(">I", 0) + b"IEND" + struct.pack(">I", zlib.crc32(b"IEND") & 0xFFFFFFFF)
            return bytes.fromhex("89504e470d0a1a0a") + ihdr_chunk + idat_chunk + padding + iend_chunk

        # 1. 64x64 icon (~863 bytes, like the blue cloud icon) must be rejected
        small_cloud_icon = make_png(64, 64, pad_bytes=750)
        self.assertEqual(get_image_dimensions(small_cloud_icon), (64, 64))
        self.assertFalse(is_valid_generated_image_bytes(small_cloud_icon))

        # 2. 64x64 icon padded above 4KB must STILL be rejected due to <200x200 dimensions
        padded_small_icon = make_png(64, 64, pad_bytes=5000)
        self.assertGreater(len(padded_small_icon), 4096)
        self.assertFalse(is_valid_generated_image_bytes(padded_small_icon))

        # 3. Genuine 512x512 generated image (>4KB and >=200x200) must be accepted
        real_generated_png = make_png(512, 512, pad_bytes=5000)
        self.assertEqual(get_image_dimensions(real_generated_png), (512, 512))
        self.assertTrue(is_valid_generated_image_bytes(real_generated_png))

        # 4. Verify JS_STATUS_AND_EXTRACTOR and JS_EXTRACT_TURN_IMAGES enforce MIN_GEN_IMG_DIM = 200 and exclude skill/citation badges
        self.assertIn("const MIN_GEN_IMG_DIM = 200;", server.JS_STATUS_AND_EXTRACTOR)
        self.assertIn("const MIN_GEN_IMG_DIM = 200;", server.JS_EXTRACT_TURN_IMAGES)
        self.assertIn("isExcludedImageContext", server.JS_STATUS_AND_EXTRACTOR)
        self.assertIn("isExcludedImageContext", server.JS_EXTRACT_TURN_IMAGES)


